<?php
/**
 * Referral History API.
 *
 * Referral History is not a standalone CRUD module — a row in
 * `referrals` is only ever CREATED automatically by api/clinic.php when a
 * Clinic Visit is saved with Referral Required = Yes. There is no POST,
 * PUT, or DELETE here — destination/reason/student/visit stay immutable,
 * and the record is never resolved/completed/cancelled either. Its only
 * job is to exist so it can be viewed, searched, and printed/generated
 * into a Referral Letter to hand to the doctor, parent, or guardian —
 * see openReferralLetterModal()/api/documents.php for that letter itself.
 */
require_once "../config/session_init.php";
session_start();
header("Content-Type: application/json");
include "../config/database.php";

if (!isset($_SESSION['user_id'])) {
    echo json_encode(["success" => false, "message" => "Unauthorized"]);
    exit();
}

require_once "../config/csrf.php";
csrf_verify();
require_once "../config/session_guard.php";
enforce_session_timeout();

// Referrals (to external medical providers) are created by the Clinic
// Module and stay Clinic/Admin-only end to end. Guidance Staff is not
// responsible for these referrals, so it has no read access here — see
// Referral History (Clinic Module) instead.
$allowedRoles = ['Administrator', 'Clinic Staff'];
if (!in_array($_SESSION['role'], $allowedRoles, true)) {
    http_response_code(403);
    echo json_encode(["success" => false, "message" => "Forbidden"]);
    exit();
}

$method = $_SERVER['REQUEST_METHOD'];

if ($method !== 'GET') {
    http_response_code(405);
    echo json_encode(["success" => false, "message" => "Only GET is supported. Referral records are auto-generated by Clinic Visits and cannot be created, edited, resolved, or deleted."]);
    exit();
}

if (isset($_GET['id'])) {
    $id = intval($_GET['id']);
    $stmt = $conn->prepare("
        SELECT r.*, s.full_name, s.student_code, s.grade_section,
               u.full_name AS clinic_staff_name,
               cv.symptoms AS visit_chief_complaint, cv.findings AS visit_findings, cv.visited_at AS visit_date
        FROM referrals r
        JOIN students s ON s.id = r.student_id
        LEFT JOIN users u ON u.id = r.clinic_staff_id
        LEFT JOIN clinic_visits cv ON cv.id = r.visit_id
        WHERE r.id = ?
    ");
    $stmt->bind_param("i", $id);
    $stmt->execute();
    echo json_encode($stmt->get_result()->fetch_assoc() ?: []);
    exit();
}

$archivedVal = (isset($_GET['archived']) && $_GET['archived'] == '1') ? 1 : 0;

// Active view (archived=0) must also hide history rows belonging to an
// archived Student, following that Student's archive state (see Archive
// Behavior Standardization spec §3/§12).
$sql = "
    SELECT r.*, s.full_name, s.student_code, s.grade_section, u.full_name AS clinic_staff_name
    FROM referrals r
    JOIN students s ON s.id = r.student_id
    LEFT JOIN users u ON u.id = r.clinic_staff_id
    WHERE r.is_archived = ?
";
if (!$archivedVal) $sql .= " AND s.is_archived = 0";
$sql .= " ORDER BY r.created_at DESC LIMIT 5000";
$stmt = $conn->prepare($sql);
$stmt->bind_param("i", $archivedVal);
$stmt->execute();
$rows = [];
$result = $stmt->get_result();
while ($row = $result->fetch_assoc()) $rows[] = $row;
echo json_encode($rows);
exit();
